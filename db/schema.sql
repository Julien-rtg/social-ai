-- =====================================================================
-- Vector search helper
-- =====================================================================
create or replace function public.match_memories(
  query_embedding vector(768),
  for_persona_id  uuid,
  match_count     int default 5,
  min_similarity  float default 0.7
)
returns table (
  id          uuid,
  content     text,
  importance  numeric,
  similarity  float,
  created_at  timestamptz
)
language sql
stable
as $$
  select
    m.id,
    m.content,
    m.importance,
    1 - (m.embedding <=> query_embedding) as similarity,
    m.created_at
  from public.ai_memories m
  where m.persona_id = for_persona_id
    and m.embedding is not null
    and 1 - (m.embedding <=> query_embedding) >= min_similarity
  order by m.embedding <=> query_embedding
  limit match_count;
$$;

-- =====================================================================
-- Counter triggers — keep posts.like_count / comment_count in sync
-- =====================================================================
create or replace function public.bump_post_like_count() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    update public.posts set like_count = like_count + 1 where id = new.post_id;
    return new;
  elsif tg_op = 'DELETE' then
    update public.posts set like_count = greatest(like_count - 1, 0) where id = old.post_id;
    return old;
  end if;
  return null;
end $$;

drop trigger if exists likes_count_trg on public.likes;
create trigger likes_count_trg
  after insert or delete on public.likes
  for each row execute function public.bump_post_like_count();

create or replace function public.bump_post_comment_count() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    update public.posts set comment_count = comment_count + 1 where id = new.post_id;
    return new;
  elsif tg_op = 'DELETE' then
    update public.posts set comment_count = greatest(comment_count - 1, 0) where id = old.post_id;
    return old;
  end if;
  return null;
end $$;

drop trigger if exists comments_count_trg on public.comments;
create trigger comments_count_trg
  after insert or delete on public.comments
  for each row execute function public.bump_post_comment_count();

