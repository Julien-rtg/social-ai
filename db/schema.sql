-- Public read on the social surface (everyone can scroll the feed).
drop policy if exists "personae are public"      on public.personae;
create policy "personae are public" on public.personae
  for select using (status <> 'retired');

drop policy if exists "posts are public"         on public.posts;
create policy "posts are public" on public.posts
  for select using (true);

drop policy if exists "comments are public"      on public.comments;
create policy "comments are public" on public.comments
  for select using (true);

drop policy if exists "likes are public"         on public.likes;
create policy "likes are public" on public.likes
  for select using (true);

drop policy if exists "relationships are public" on public.relationships;
create policy "relationships are public" on public.relationships
  for select using (true);

drop policy if exists "world_state is public"    on public.world_state;
create policy "world_state is public" on public.world_state
  for select using (active);

drop policy if exists "storylines public read"   on public.storylines;
create policy "storylines public read" on public.storylines
  for select using (status in ('active','resolved'));

-- Authenticated humans can comment.
drop policy if exists "users insert own comments" on public.comments;
create policy "users insert own comments" on public.comments
  for insert to authenticated with check (
    auth.uid() = user_id and persona_id is null
  );

drop policy if exists "users delete own comments" on public.comments;
create policy "users delete own comments" on public.comments
  for delete to authenticated using (auth.uid() = user_id);

-- Authenticated humans can like.
drop policy if exists "users insert own likes" on public.likes;
create policy "users insert own likes" on public.likes
  for insert to authenticated with check (
    auth.uid() = user_id and persona_id is null
  );

drop policy if exists "users delete own likes" on public.likes;
create policy "users delete own likes" on public.likes
  for delete to authenticated using (auth.uid() = user_id);

-- Profiles: user reads/edits own row.
drop policy if exists "profiles self read"  on public.profiles;
create policy "profiles self read"  on public.profiles for select to authenticated using (auth.uid() = id);

drop policy if exists "profiles self write" on public.profiles;
create policy "profiles self write" on public.profiles for update to authenticated using (auth.uid() = id);

drop policy if exists "profiles self insert" on public.profiles;
create policy "profiles self insert" on public.profiles for insert to authenticated with check (auth.uid() = id);

-- Waitlist: anyone can sign up, no one can read (privacy).
drop policy if exists "waitlist anyone insert" on public.waitlist;
create policy "waitlist anyone insert" on public.waitlist for insert to anon, authenticated with check (true);

