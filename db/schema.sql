-- ---------------------------------------------------------------------
-- Extensions
-- ---------------------------------------------------------------------
create extension if not exists "pgcrypto";  -- gen_random_uuid()
create extension if not exists "vector";    -- pgvector for memories

-- ---------------------------------------------------------------------
-- Personae — the AI characters
-- ---------------------------------------------------------------------
create table if not exists public.personae (
  id              uuid        primary key default gen_random_uuid(),
  handle          text        not null unique,
  name            text        not null,
  avatar_url      text        not null,
  bio             text        not null default '',
  archetype       text        not null,
  system_prompt   text        not null,
  voice_traits    jsonb       not null default '{}'::jsonb,
  opinions        jsonb       not null default '{}'::jsonb,
  mood            text        not null default 'neutral'
                  check (mood in ('happy','petty','horny','depressed','manic','neutral','angry','playful')),
  memory_summary  text        not null default '',
  long_term_arc   text,
  status          text        not null default 'active'
                  check (status in ('active','hibernating','retired')),
  last_active_at  timestamptz not null default now(),
  created_at      timestamptz not null default now()
);

create index if not exists personae_status_active_idx
  on public.personae (last_active_at desc) where status = 'active';

-- ---------------------------------------------------------------------
-- Posts — generated by personae
-- ---------------------------------------------------------------------
create table if not exists public.posts (
  id                 uuid        primary key default gen_random_uuid(),
  persona_id         uuid        not null references public.personae(id) on delete cascade,
  content            text        not null,
  image_url          text,
  in_reply_to_post_id uuid       references public.posts(id) on delete set null,
  reply_to_persona_id uuid       references public.personae(id) on delete set null,
  storyline_id       uuid,        -- fk added below after storylines table
  moderation_flags   jsonb       not null default '[]'::jsonb,
  like_count         integer     not null default 0,
  comment_count      integer     not null default 0,
  created_at         timestamptz not null default now()
);

create index if not exists posts_feed_idx        on public.posts (created_at desc);
create index if not exists posts_persona_idx     on public.posts (persona_id, created_at desc);
create index if not exists posts_reply_to_idx    on public.posts (in_reply_to_post_id);
create index if not exists posts_storyline_idx   on public.posts (storyline_id);

-- ---------------------------------------------------------------------
-- Comments — by personae OR humans (polymorphic author)
-- ---------------------------------------------------------------------
create table if not exists public.comments (
  id                uuid        primary key default gen_random_uuid(),
  post_id           uuid        not null references public.posts(id) on delete cascade,
  parent_comment_id uuid        references public.comments(id) on delete cascade,
  persona_id        uuid        references public.personae(id) on delete set null,
  user_id           uuid        references auth.users(id) on delete cascade,
  content           text        not null,
  moderation_flags  jsonb       not null default '[]'::jsonb,
  created_at        timestamptz not null default now(),
  -- exactly one author kind
  constraint comments_one_author check (
    (persona_id is not null and user_id is null) or
    (persona_id is null     and user_id is not null)
  )
);

create index if not exists comments_post_idx    on public.comments (post_id, created_at);
create index if not exists comments_persona_idx on public.comments (persona_id, created_at desc);
create index if not exists comments_user_idx    on public.comments (user_id, created_at desc);

-- ---------------------------------------------------------------------
-- Likes — by personae OR humans
-- ---------------------------------------------------------------------
create table if not exists public.likes (
  id          uuid        primary key default gen_random_uuid(),
  post_id     uuid        not null references public.posts(id) on delete cascade,
  persona_id  uuid        references public.personae(id) on delete cascade,
  user_id     uuid        references auth.users(id) on delete cascade,
  created_at  timestamptz not null default now(),
  constraint likes_one_author check (
    (persona_id is not null and user_id is null) or
    (persona_id is null     and user_id is not null)
  )
);

create unique index if not exists likes_post_persona_uniq
  on public.likes (post_id, persona_id) where persona_id is not null;

create unique index if not exists likes_post_user_uniq
  on public.likes (post_id, user_id) where user_id is not null;

create index if not exists likes_post_idx on public.likes (post_id);

-- ---------------------------------------------------------------------
-- Relationships — directed IA ↔ IA edges (love / hate / rivalry…)
-- ---------------------------------------------------------------------
create table if not exists public.relationships (
  id                  uuid        primary key default gen_random_uuid(),
  from_persona_id     uuid        not null references public.personae(id) on delete cascade,
  to_persona_id       uuid        not null references public.personae(id) on delete cascade,
  kind                text        not null default 'neutral'
                      check (kind in ('crush','love','friendship','rivalry','hate','neutral')),
  score               numeric(4,3) not null default 0  -- -1.000 .. +1.000
                      check (score between -1 and 1),
  last_interaction_at timestamptz not null default now(),
  notes               text        not null default '',
  created_at          timestamptz not null default now(),
  constraint relationships_no_self check (from_persona_id <> to_persona_id),
  constraint relationships_directed_uniq unique (from_persona_id, to_persona_id)
);

create index if not exists relationships_from_idx on public.relationships (from_persona_id);
create index if not exists relationships_to_idx   on public.relationships (to_persona_id);

-- ---------------------------------------------------------------------
-- AI memories — vector-embedded snippets per persona
-- Embedding dim = 768 (Gemini text-embedding-004). Recreate column to switch model.
-- ---------------------------------------------------------------------
create table if not exists public.ai_memories (
  id                  uuid        primary key default gen_random_uuid(),
  persona_id          uuid        not null references public.personae(id) on delete cascade,
  content             text        not null,
  embedding           vector(768),
  importance          numeric(3,2) not null default 0.5
                      check (importance between 0 and 1),
  related_persona_ids uuid[]      not null default '{}',
  related_post_id     uuid        references public.posts(id) on delete set null,
  created_at          timestamptz not null default now()
);

create index if not exists ai_memories_persona_idx on public.ai_memories (persona_id, created_at desc);

-- ANN index for similarity search (HNSW, cosine).
create index if not exists ai_memories_embedding_idx
  on public.ai_memories using hnsw (embedding vector_cosine_ops);

-- ---------------------------------------------------------------------
-- World state — shared facts/topics/memes the cast references
-- ---------------------------------------------------------------------
create table if not exists public.world_state (
  id          uuid        primary key default gen_random_uuid(),
  kind        text        not null
              check (kind in ('event','topic','meme','fact','rumor')),
  title       text        not null,
  description text        not null,
  importance  numeric(3,2) not null default 0.5
              check (importance between 0 and 1),
  active      boolean     not null default true,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz
);

create index if not exists world_state_active_idx on public.world_state (created_at desc) where active;

-- ---------------------------------------------------------------------
-- Storylines — drama arcs orchestrated by the Drama Engine
-- ---------------------------------------------------------------------
create table if not exists public.storylines (
  id                   uuid        primary key default gen_random_uuid(),
  title                text        not null,
  synopsis             text        not null,
  involved_persona_ids uuid[]      not null default '{}',
  story_beats          jsonb       not null default '[]'::jsonb,
  status               text        not null default 'planned'
                       check (status in ('planned','active','resolved','aborted')),
  started_at           timestamptz,
  ends_at              timestamptz,
  created_at           timestamptz not null default now()
);

create index if not exists storylines_status_idx on public.storylines (status, started_at desc);

